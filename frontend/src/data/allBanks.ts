export const BANK_CATEGORIES = [
  { key: 'ALL', label: 'All Banks' },
  { key: 'POPULAR', label: 'Popular' },
  { key: 'PUBLIC', label: 'Public Sector' },
  { key: 'PRIVATE', label: 'Private Sector' },
  { key: 'PAYMENTS_SFB', label: 'Payments & SFB' },
  { key: 'FOREIGN', label: 'Foreign Banks' },
] as const;

export function searchBanks(query: string, category: string = 'ALL'): IndianBankInfo[] {
  const cleanQ = query.trim().toLowerCase();
  return ALL_INDIAN_BANKS.filter((b) => {
    const matchesCategory =
      category === 'ALL'
        ? true
        : category === 'POPULAR'
        ? b.popular
        : b.category === category;

    if (!matchesCategory) return false;
    if (!cleanQ) return true;

    return (
      b.name.toLowerCase().includes(cleanQ) ||
      b.fullName.toLowerCase().includes(cleanQ) ||
      b.shortCode.toLowerCase().includes(cleanQ) ||
      b.ifscPrefix.toLowerCase().includes(cleanQ) ||
      b.defaultVpaDomain.toLowerCase().includes(cleanQ)
    );
  });
}
